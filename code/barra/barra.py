def build_style_cache():
    cache = {}
    for sid, defs in STYLE_DEFS.items():
        cache[sid] = {
            "font": Font.from_tree(fromstring(defs["font"])),
            "fill": Fill.from_tree(fromstring(defs["fill"])),
            "border": Border.from_tree(fromstring(defs["border"])),
            "alignment": Alignment.from_tree(fromstring(defs["alignment"])),
            "protection": Protection.from_tree(fromstring(defs["protection"])),
            "number_format": defs["number_format"],
        }
    return cache

def build_dxf_cache():
    return {i: DifferentialStyle.from_tree(fromstring(xml)) for i, xml in DXF_DEFS.items()}

def apply_style(cell, style_cache, sid):
    st = style_cache[sid]
    cell.font = copy(st["font"])
    cell.fill = copy(st["fill"])
    cell.border = copy(st["border"])
    cell.alignment = copy(st["alignment"])
    cell.protection = copy(st["protection"])
    cell.number_format = st["number_format"]

def populate_sheet(ws, data, style_cache):
    if data["show_grid_lines"] is not None:
        ws.sheet_view.showGridLines = data["show_grid_lines"]
    for col_letter, width in data["col_widths"].items():
        ws.column_dimensions[col_letter].width = width
    for row_idx, height in data["row_heights"].items():
        ws.row_dimensions[row_idx].height = height
    for coord, value, sid in data["cells"]:
        cell = ws[coord]
        if value is not None:
            cell.value = value
        apply_style(cell, style_cache, sid)
    for coord, (text, author, width, height) in COMMENTS.get(ws.title, {}).items():
        comment = Comment(text, author)
        comment.width = width
        comment.height = height
        ws[coord].comment = comment
    for merged_range in data["merged_cells"]:
        ws.merge_cells(merged_range)
    for dv_data in DATA_VALIDATIONS.get(ws.title, []):
        dv = DataValidation(type=dv_data["type"], formula1=dv_data["formula1"], formula2=dv_data["formula2"], allow_blank=dv_data["allowBlank"])
        dv.showDropDown = dv_data["showDropDown"]
        dv.showErrorMessage = dv_data["showErrorMessage"]
        dv.showInputMessage = dv_data["showInputMessage"]
        if dv_data["operator"] is not None:
            dv.operator = dv_data["operator"]
        ws.add_data_validation(dv)
        dv.add(dv_data["sqref"])
    return ws

def add_conditional_formatting(ws, dxf_cache):
    for rule_data in CONDITIONAL_FORMATTING.get(ws.title, []):
        rule = Rule(type=rule_data["type"], dxf=copy(dxf_cache[rule_data["dxf_id"]]), formula=list(rule_data["formula"]))
        if rule_data["operator"] is not None:
            rule.operator = rule_data["operator"]
        if rule_data["stopIfTrue"] is not None:
            rule.stopIfTrue = rule_data["stopIfTrue"]
        ws.conditional_formatting.add(rule_data["range"], rule)

def build_workbook(output_path: str | Path = "barra_enterprise_stock_only_no_etf_enhanced_from_scratch.xlsx"):
    wb = Workbook()
    default_ws = wb.active
    wb.remove(default_ws)
    wb.properties.creator = "openpyxl"
    wb.properties.created = datetime(2026, 3, 26, 7, 18, 7, 885592)
    wb.properties.modified = datetime(2026, 3, 26, 7, 18, 7, 885592)
    wb.calculation.fullCalcOnLoad = True
    style_cache = build_style_cache()
    dxf_cache = build_dxf_cache()
    for title in SHEET_ORDER:
        ws = wb.create_sheet(title)
        populate_sheet(ws, SHEET_DEFS[title], style_cache)
    for ws in wb.worksheets:
        add_conditional_formatting(ws, dxf_cache)
    wb.active = 0
    output_path = Path(output_path)
    wb.save(output_path)
    return output_path

