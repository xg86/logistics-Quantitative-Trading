def add_table(ws, name, ref):
    tbl = Table(displayName=name, ref=ref)
    tbl.tableStyleInfo = TableStyleInfo(
        name="TableStyleMedium9",
        showFirstColumn=False,
        showLastColumn=False,
        showRowStripes=True,
        showColumnStripes=False
    )
    ws.add_table(tbl)

def apply_widths(ws, widths):
    for col, w in widths.items():
        ws.column_dimensions[col].width = w

def apply_heights(ws, heights):
    for r, h in heights.items():
        ws.row_dimensions[r].height = h

def apply_number_formats(ws, formats):
    # formats: list[(row, col, number_format)]
    for r, c, fmt in formats:
        ws.cell(row=r, column=c).number_format = fmt

def style_ws(ws):
    # Simple consistent styling similar to the demo workbook
    thin = Side(style="thin", color="D0D0D0")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    header_fill = PatternFill("solid", fgColor="1F4E79")
    header_font = Font(color="FFFFFF", bold=True)
    header_alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    body_alignment = Alignment(vertical="top", wrap_text=True)

    max_row = ws.max_row
    max_col = ws.max_column

    # header row
    for c in range(1, max_col + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = header_alignment
        cell.border = border

    # body
    for r in range(2, max_row + 1):
        for c in range(1, max_col + 1):
            cell = ws.cell(row=r, column=c)
            cell.alignment = body_alignment
            cell.border = border

def build_workbook(output_path: str):
    wb = Workbook()
    # remove default sheet
    wb.remove(wb.active)

    # create sheets in order
    for name in SHEET_ORDER:
        wb.create_sheet(title=name)

    # populate
    for name in SHEET_ORDER:
        ws = wb[name]
        ws.freeze_panes = "A2"

        rows = SHEET_DATA[name]
        for row in rows:
            ws.append(list(row))

        apply_widths(ws, COL_WIDTHS.get(name, {}))
        apply_heights(ws, ROW_HEIGHTS.get(name, {}))
        apply_number_formats(ws, NUMBER_FORMATS.get(name, []))

        # tables
        for t_name, t_ref in TABLES.get(name, []):
            add_table(ws, t_name, t_ref)

        style_ws(ws)

    wb.save(output_path)

